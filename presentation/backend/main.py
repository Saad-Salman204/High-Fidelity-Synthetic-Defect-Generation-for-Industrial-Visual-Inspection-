    """Serve only an image generated by this presentation app."""
    if len(image_id) != 32 or any(character not in "0123456789abcdef" for character in image_id):
        raise HTTPException(404, "Image not found.")
    path = (DEMO_ROOT / "generated" / f"{image_id}.png").resolve()
    if not path.is_relative_to(DEMO_ROOT.resolve()) or not path.is_file():
        raise HTTPException(404, "Image not found.")
