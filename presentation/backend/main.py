@app.post("/api/generate")
async def generate(body: dict) -> dict:
    """Generate one seeded image using the existing local SD 1.5 + LoRA path."""
    class_name = body.get("class_name")
    seed = body.get("seed", 42)
    if not isinstance(class_name, str) or type(seed) is not int:
        raise HTTPException(422, "Provide a defect class and integer seed.")
    try:
        return await run_in_threadpool(runtime.generate, class_name, seed)
    except FileNotFoundError as exc:
        raise HTTPException(503, str(exc)) from exc
    except (OSError, RuntimeError, ValueError, KeyError, TypeError) as exc:
        message = str(exc)
        code = 503 if "GPU memory" in message or "CUDA" in message else 422
        raise HTTPException(code, message) from exc


def _decode_upload(payload: bytes) -> Image.Image:
    if not payload:
        raise HTTPException(400, "The uploaded file is empty.")
    try:
        with Image.open(io.BytesIO(payload)) as checked:
            if checked.format not in ALLOWED_FORMATS:
                raise HTTPException(415, "Upload a PNG, JPEG, or WebP image.")
            if checked.width < 16 or checked.height < 16:
                raise HTTPException(400, "Image dimensions must be at least 16 × 16 pixels.")
            if checked.width * checked.height > MAX_IMAGE_PIXELS:
                raise HTTPException(413, "Image is too large to process (limit: 40 megapixels).")
            checked.verify()
        with Image.open(io.BytesIO(payload)) as image:
            return image.convert("RGB").copy()
    except UnidentifiedImageError as exc:
        raise HTTPException(400, "The upload is not a readable image.") from exc
    except OSError as exc:
        raise HTTPException(400, "The image could not be decoded.") from exc


async def _read_image(file: UploadFile) -> Image.Image:
    if file.content_type not in {"image/png", "image/jpeg", "image/webp"}:
        raise HTTPException(415, "Upload a PNG, JPEG, or WebP image.")
    payload = await file.read(MAX_UPLOAD_BYTES + 1)
    if len(payload) > MAX_UPLOAD_BYTES:
        raise HTTPException(413, "Image upload exceeds the 10 MB limit.")
    return _decode_upload(payload)


@app.post("/api/classify")
async def classify_upload(
    file: Annotated[UploadFile, File()],
    arm: str = Query("real_only"),
    seed: int = Query(42),
) -> dict:
    """Classify a validated user image with an existing saved ResNet checkpoint."""
    image = await _read_image(file)
    try:
        return await run_in_threadpool(runtime.classify, image, arm, seed)
    except FileNotFoundError as exc:
        raise HTTPException(503, str(exc)) from exc
    except (OSError, RuntimeError, ValueError, KeyError) as exc:
        message = str(exc)
        code = 503 if "GPU memory" in message or "CUDA" in message else 422
        raise HTTPException(code, message) from exc


@app.post("/api/classify-generated/{image_id}")
async def classify_generated(
    image_id: str,
    arm: str = Query("real_only"),
    seed: int = Query(42),
) -> dict:
    """Classify a demonstration image previously generated by this local app."""
    if len(image_id) != 32 or any(character not in "0123456789abcdef" for character in image_id):
        raise HTTPException(404, "Unknown demonstration image.")
    path = (DEMO_ROOT / "generated" / f"{image_id}.png").resolve()
    if not path.is_relative_to(DEMO_ROOT.resolve()) or not path.is_file():
        raise HTTPException(404, "Unknown demonstration image.")
    try:
        with Image.open(path) as image:
            image.load()
            decoded = image.convert("RGB")
        return await run_in_threadpool(runtime.classify, decoded, arm, seed)
    except (OSError, RuntimeError, ValueError, KeyError) as exc:
        raise HTTPException(422, str(exc)) from exc


