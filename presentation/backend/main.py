@app.get("/api/research/results")
def research_results() -> dict:
    """Serve the verified Phase 1 JSON/CSV results without recalculating scores."""
    try:
        results = runtime.research_results()
    except (OSError, ValueError, KeyError) as exc:
        raise HTTPException(503, f"Phase 1 results are unavailable: {exc}") from exc
    if results["status"] != "completed" or len(results["runs"]) != 9:
        raise HTTPException(503, "Phase 1 evaluation is incomplete; results are not presented.")
    return results


@app.get("/api/research/metrics")
def research_metrics() -> dict:
    """Return measured arm-level mean and sample standard deviation."""
    return research_results()["aggregates"]


@app.get("/api/research/experiments")
def experiments() -> list[dict]:
    """Return individual measured results for all nine arm and seed runs."""
    return research_results()["runs"]


@app.get("/api/gallery")
def gallery(limit_per_class: int = Query(3, ge=1, le=12)) -> dict:
    """Return verified exploratory samples, explicitly marked as not accepted."""
    try:
        records = runtime.gallery(limit_per_class)
    except (OSError, ValueError, KeyError) as exc:
        raise HTTPException(503, f"Gallery is unavailable: {exc}") from exc
    return {
        "items": records,
        "human_review_status": "exploratory_samples_only_not_acceptance_decisions",
        "total_returned": len(records),
    }


@app.get("/api/gallery/images/{image_id}")
def gallery_image(image_id: str) -> FileResponse:
    """Resolve an image ID through the fixed review selection, never a path input."""
    try:
        path = runtime.gallery_image(image_id)
    except FileNotFoundError as exc:
        raise HTTPException(404, str(exc)) from exc
    except (OSError, ValueError) as exc:
        raise HTTPException(409, str(exc)) from exc
    return FileResponse(path, media_type="image/png")


@app.get("/api/figures/{filename}")
def figure(filename: str) -> FileResponse:
    """Serve one of the known Phase 1 publication figures."""
    if filename not in FIGURES:
        raise HTTPException(404, "Unknown evaluation figure.")
    figure_root = EVALUATION_ROOT if EVALUATION_ROOT.is_dir() else PACKAGED_RESEARCH_ROOT
    path = (figure_root / "figures" / filename).resolve()
    if not path.is_relative_to(figure_root.resolve()) or not path.is_file():
        raise HTTPException(404, "Evaluation figure not found.")
    media_type = "application/pdf" if filename.endswith(".pdf") else "image/png"
    return FileResponse(path, media_type=media_type)


